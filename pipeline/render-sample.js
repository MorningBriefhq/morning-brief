const headerComment =
  "<!--\n" +
  "  SAMPLE RENDER of email/template.html — for design approval only.\n" +
  "  All content below is illustrative sample copy, not real market data.\n" +
  "  Generated by pipeline/render-sample.js — do not hand-edit.\n" +
  "-->";

function build(theme) {
  let html = renderTemplate(template, data, { theme });
  html = html.replace(
    "<title>Morning Brief</title>",
    `<title>Morning Brief — ${DATE_LONG}</title>`
  );
  html = html.replace("<head>", `<head>\n${headerComment}`);
  return html;
}

